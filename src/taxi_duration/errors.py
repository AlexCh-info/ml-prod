"""Иерархия ожидаемых ошибок проекта.

Всё, что наследует ``TaxiError``, CLI превращает в одну строку в stderr и код
возврата 1 без трассировки. Любое другое исключение считается багом и
логируется с трассировкой.
"""


class TaxiError(Exception):
    """Базовая ожидаемая ошибка приложения."""


class ConfigError(TaxiError):
    """Конфиг не найден, не читается или не проходит валидацию."""


class DataError(TaxiError):
    """Входные данные отсутствуют или не соответствуют ожиданиям."""


class DataValidationError(DataError):
    """Данные нарушили хотя бы одно critical-ожидание контракта (этап 03, quality gate)."""
